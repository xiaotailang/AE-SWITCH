import { readFile, writeFile } from "node:fs/promises";
const content = JSON.parse(
  await readFile(
    new URL("../src/content/tutorial.json", import.meta.url),
    "utf8",
  ),
);
const { version } = JSON.parse(
  await readFile(new URL("../package.json", import.meta.url), "utf8"),
);
const { githubRepository } = JSON.parse(
  await readFile(new URL("../release-config.json", import.meta.url), "utf8"),
);
const repository =
  typeof githubRepository === "string" &&
  /^[A-Za-z0-9][A-Za-z0-9-]{0,38}\/[A-Za-z0-9._-]{1,100}$/.test(
    githubRepository,
  )
    ? githubRepository
    : null;
const projectLinks = repository
  ? `[下载最新程序](https://github.com/${repository}/releases/latest) · [返回项目首页](../README.md) · [反馈问题](https://github.com/${repository}/issues)`
  : "[返回项目首页](../README.md) · 当前修改版仓库尚未设置，下载及反馈链接待绑定。";
const releaseLink = repository
  ? `- [GitHub Releases 与下载附件](https://github.com/${repository}/releases/latest)`
  : "- 当前修改版仓库尚未设置；不会使用上游项目的发行包作为本版本更新。";
const anchors = content.topics
  .map((t) => `- [${t.title}](#${t.id})`)
  .join("\n");
const sections = content.topics
  .map((t) => {
    const body = t.sections
      .map((s) =>
        [
          `### ${s.title}`,
          s.steps?.map((step, i) => `${i + 1}. ${step}`).join("\n"),
          s.paragraphs?.join("\n\n"),
          s.bullets?.map((item) => `- ${item}`).join("\n"),
          s.table &&
            [
              `| ${s.table.headers.join(" | ")} |`,
              `| ${s.table.headers.map(() => "---").join(" | ")} |`,
              ...s.table.rows.map((row) => `| ${row.join(" | ")} |`),
            ].join("\n"),
        ]
          .filter(Boolean)
          .join("\n\n"),
      )
      .join("\n\n");
    return `<a id="${t.id}"></a>\n\n## ${t.title}\n\n${t.summary}\n\n${body}`;
  })
  .join("\n\n");
const markdown = `<!-- Generated by scripts/generate-tutorial.mjs from src/content/tutorial.json. -->
# ${content.title}

适用版本：**v${version}** · Windows x64

${content.intro}

${projectLinks}

## 教程目录

${anchors}

${sections}

## 在线资料

${releaseLink}
- [更新记录](../CHANGELOG.md)
- [配置与隔离验证说明](qa-inventory.md)

本文与软件内「使用说明」共用一份内容。维护时修改 \`src/content/tutorial.json\`，运行 \`corepack pnpm docs:generate\`；\`corepack pnpm docs:check\` 检查两端说明是否一致。
`;
const file = new URL("../docs/tutorial.md", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(file, "utf8")) !== markdown)
    throw new Error("教程未同步：请运行 corepack pnpm docs:generate");
  console.log("软件内教程与 GitHub 教程一致");
} else {
  await writeFile(file, markdown, "utf8");
  console.log("已生成 docs/tutorial.md");
}
